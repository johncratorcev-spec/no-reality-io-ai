#!/usr/bin/env node
/**
 * Генерирует src/lib/posts.snapshot.ts — встроенную копию data/posts.csv.
 *
 * Зачем: на serverless (Netlify) функция собирается из трейс-файлов Next;
 * если CSV вдруг не попал в бандл, лента всё равно работает — парсится
 * встроенная копия. Обновляется при каждой сборке (npm prebuild),
 * поэтому всегда в sync с репозиторием.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const csvPath = path.join(root, "data", "posts.csv");
const outPath = path.join(root, "src", "lib", "posts.snapshot.ts");

let raw;
try {
  raw = fs.readFileSync(csvPath, "utf-8");
} catch {
  console.error("[snapshot] data/posts.csv не найден — снапшот не обновлён");
  process.exit(1);
}

const body = `// @generated by scripts/gen-posts-snapshot.mjs (npm prebuild) — не редактировать вручную
// Встроенная копия data/posts.csv: фолбэк для serverless-сред,
// где CSV может не попасть в бандл функции.
export const POSTS_CSV_SNAPSHOT = ${JSON.stringify(raw)};
`;

fs.writeFileSync(outPath, body);
const lines = raw.trimEnd().split("\n").length;
console.log(`[snapshot] src/lib/posts.snapshot.ts обновлён (${lines - 1} постов)`);
