#!/usr/bin/env node
/**
 * Генерирует src/lib/prompts.snapshot.ts — встроенную копию data/prompts.csv.
 *
 * Зачем отдельный файл (а не колонка в posts.csv): prompt_full — секрет,
 * который нельзя отдавать на клиент. Снапшот импортируется ТОЛЬКО
 * серверными модулями (lib/prompts/paid.ts), поэтому полный текст промпта
 * никогда не попадает в клиентский бандл и в RSC-пейлоад.
 *
 * Обновляется на каждой сборке (npm run build) — всегда в sync с репозиторием.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const csvPath = path.join(root, "data", "prompts.csv");
const outPath = path.join(root, "src", "lib", "prompts.snapshot.ts");

let raw;
try {
  raw = fs.readFileSync(csvPath, "utf-8");
} catch {
  console.error("[prompts-snapshot] data/prompts.csv не найден — пишу пустой снапшот");
  raw = "utm_code,prompt_full\n";
}

const body = `// @generated by scripts/gen-prompts-snapshot.mjs (npm run build) — не редактировать вручную
// Встроенная копия data/prompts.csv. СЕРВЕР-ОНИ: импортировать только из
// серверных модулей — полный текст промптов не должен попасть на клиент.
export const PROMPTS_CSV_SNAPSHOT = ${JSON.stringify(raw)};
`;

fs.writeFileSync(outPath, body);
const rows = raw.trimEnd().split("\n").length - 1;
console.log(`[prompts-snapshot] src/lib/prompts.snapshot.ts обновлён (${rows} промптов)`);
